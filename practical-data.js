export function normalizePracticalState(value) {
  const valid = new Set(practicalUnits.map(item => item.id));
  const input = value && typeof value === 'object' ? value : {};
  return {
    completed: Array.isArray(input.completed) ? [...new Set(input.completed.filter(id => valid.has(id)))] : [],
    drafts: Object.fromEntries(Object.entries(input.drafts || {}).filter(([id, text]) => valid.has(id) && typeof text === 'string')),
    checks: Object.fromEntries(Object.entries(input.checks || {}).filter(([id, list]) => valid.has(id) && Array.isArray(list)).map(([id, list]) => [id, [...new Set(list.filter(n => Number.isInteger(n) && n >= 0 && n < 3))]]))
  };
}

export function practicalProgress(value, areaId = null) {
  const state = normalizePracticalState(value);
  const units = practicalUnits.filter(item => !areaId || item.areaId === areaId);
  return { total: units.length, completed: units.filter(item => state.completed.includes(item.id)).length,
    written: units.filter(item => state.drafts[item.id]?.trim()).length,
    checked: units.reduce((sum, item) => sum + (state.checks[item.id]?.length || 0), 0), possible: units.length * 3 };
}
