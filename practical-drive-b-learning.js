import { driveQuestionsB } from './practical-drive-b.js';

const questionByNumber = number => driveQuestionsB.find(q => q.id === `drive-b-${String(number).padStart(2,'0')}`);
function lesson(title, objectives, notes, comparisons, numbers, exampleNumber, selfExplain, answerFrame) {
  const questions = numbers.map(questionByNumber);
  const example = questionByNumber(exampleNumber);
  return {
    title,
    provenance:'구글드라이브 제공 교재 사진 · 모의고사와 단원별 점검문제를 연결한 실기 기본이론 보충',
    scope:'사진에서 확인한 범위를 바탕으로 개념·판단 순서·답안 표현을 다시 설명했습니다. 법령·계약 수치는 해당 문항에 적은 적용 범위와 참고자료를 함께 확인합니다. 검토일: 2026-10-24.',
    questionSource:'review',
    scopeNote:'예제의 조건과 숫자는 학습용 전제입니다. 서로 다른 계약 유형의 기준을 하나의 공통 기준으로 바꾸어 적용하지 않습니다.',
    objectives,notes:notes.map(([title,text])=>({title,text})),
    comparisons:comparisons.map(([title,items])=>({title,items})),
    examples:[{title:`따라 쓰는 예제 · ${example.title}`,condition:example.scenario,
      steps:example.answer.map((answer,index)=>[`${index+1}단계`,`${answer} 풀이: ${example.reasons[index]}`]),
      conclusion:`답안에 남길 순서: ${example.blueprint.join(' / ')}`}],
    answerFrame,selfExplain,questions:questions.map(q=>q.id),
    refs:[...new Map(questions.flatMap(q=>q.refs).map(r=>[r.url,r])).values()]
  };
}

